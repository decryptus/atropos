"""Technology-independent persistence and delivery contracts.

Storage owns admission, deduplication, leases, exclusion and the durable outbox.
Delivery is at-least-once; receiving a message never grants execution authority.
"""
from __future__ import annotations
from dataclasses import dataclass
from typing import Protocol


class Conflict(ValueError):
    pass


class QueueFull(Conflict):
    """Admission refused without committing any state, proof or audit."""


@dataclass(frozen=True)
class Claim:
    state: dict
    token: str
    message_id: str
    consumer: str


class DeliveryQueue(Protocol):
    def send(self, delivery_id: str, run_id: str): ...
    def receive(self, consumer: str, block_ms: int): ...
    def acknowledge(self, delivery_id: str): ...
    def close(self): ...


class WorkflowStore(Protocol):
    lease_ms: int
    client: EvidenceStore
    prefix: str
    def enqueue(self, workflow, inputs, target, deduplication_key=None, attribution=None, **evidence): ...
    def get(self, run_id): ...
    def receive(self, consumer, cursor='0-0', block_ms=1000): ...
    def claim(self, message_id, run_id, consumer): ...
    def heartbeat(self, claim): ...
    def finish(self, claim, state, delay=0): ...
    def resolve(self, run_id, outcome): ...
    def reconcile(self, run_id, outcome, *, expected_state, reconciliation, audit): ...
    def now(self): ...


class EvidenceStore(Protocol):
    """Opaque condition values; writes share the workflow admission transaction."""
    def get(self, key: str) -> str | None: ...
    def set(self, key: str, value: str, ex: int | None = None): ...


class StorageBackend(Protocol):
    """One transaction domain for rules, evidence and workflow admission."""
    client: EvidenceStore
    def workflow_store(self, namespace, queue=None): ...
    def repository(self, organization, namespace): ...
    def lifecycle_store(self, repository): ...
    def close(self): ...


class InterventionIndex(Protocol):
    """Optional authorized search capability; filters/count/page run in storage.

    snapshot pins count/page consistency. scopes lists revision/mode pairs for
    the exact owner and rule; page accepts only application-authorized targets.
    """
    def snapshot(self): ...
    def scopes(self, subject, organization, rule): ...
    def page(self, subject, organization, rule, query, scopes): ...
