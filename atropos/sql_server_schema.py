"""Constrained server schemas. DDL is generated only from fixed engine constants."""
from .sqlite_schema import STATUSES

SCHEMA_VERSION = 1
TABLES = frozenset({'storage_metadata', 'records', 'journal', 'runs', 'admissions'})


def schema(dialect, collation=None):
    pg = dialect == 'postgresql'
    collate = ' COLLATE "C"' if pg else ''
    integer = 'BIGINT' if pg else 'BIGINT UNSIGNED'
    floating = 'DOUBLE PRECISION' if pg else 'DOUBLE'
    large_text = 'TEXT' if pg else 'LONGTEXT'
    suffix = '' if pg else ' ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=' + collation

    def regex(column, pattern):
        return column + (' ~ ' if pg else ' REGEXP ') + "'" + pattern + "'"

    def text(column, length):
        return f'{column} VARCHAR({length}){collate} NOT NULL CHECK(char_length({column}) BETWEEN 1 AND {length})'

    def fixed(column, length, nullable=False):
        return (f'{column} CHAR({length}){collate} ' + ('NULL' if nullable else 'NOT NULL')
                + f" CHECK(char_length({column})={length} AND " + regex(column, '^[0-9a-f]{' + str(length) + '}$') + ')')

    def timestamp(column, nullable=False):
        return f"{column} {floating} {'NULL' if nullable else 'NOT NULL'} CHECK({column} BETWEEN 0 AND 253402300799)"

    def extracted(column, path, raw=False):
        if pg:
            return f"({column}::jsonb {'#>' if raw else '#>>'} '{{{path.replace('.', ',')}}}')"
        value = f"JSON_EXTRACT({column}, '$.{path}')"
        return value if raw else f'JSON_UNQUOTE({value})'

    def kind(column, path):
        return ('jsonb_typeof' if pg else 'JSON_TYPE') + '(' + extracted(column, path, True) + ')'

    def mismatch(left, right):
        return f'{left} IS DISTINCT FROM {right}' if pg else f'NOT ({left} <=> {right})'

    identity = [f'CHECK(({extracted("state", path)}={column}) IS TRUE)'
                for path, column in [('id', 'id'), ('status', 'status'), ('target', 'target'), ('workflow.name', 'workflow')]]
    numeric = "'number'" if pg else "'INTEGER','DOUBLE'"
    numeric_value = extracted('state', 'created_at')
    cast_number = f'CAST({numeric_value} AS {"DOUBLE PRECISION" if pg else "DOUBLE"})'
    identity += [f"CHECK(({kind('state', 'created_at')} IN ({numeric}) AND {cast_number}=created) IS TRUE)"]
    valid_json = 'jsonb_typeof(state::jsonb)=\'object\'' if pg else "JSON_VALID(state) AND JSON_TYPE(JSON_EXTRACT(state,'$'))='OBJECT'"
    journal_id = ('BIGINT GENERATED BY DEFAULT AS IDENTITY' if pg else 'BIGINT UNSIGNED AUTO_INCREMENT')
    journal_check = ' CHECK(id BETWEEN 1 AND 9223372036854775807)' if pg else ''
    ddl = [
        f'''CREATE TABLE storage_metadata (id SMALLINT{' UNSIGNED' if not pg else ''} PRIMARY KEY CHECK(id=1),
            version INTEGER{' UNSIGNED' if not pg else ''} NOT NULL CHECK(version>0),
            {fixed('schema_hash',64)}){suffix}''',
        f'''CREATE TABLE records ({text('"key"',512)}, value {large_text} NOT NULL,
            {timestamp('expires',True)}, PRIMARY KEY("key")){suffix}''',
        f'''CREATE TABLE journal (id {journal_id} PRIMARY KEY{journal_check},
            {text('"key"',512)}, value {large_text} NOT NULL){suffix}''',
        'CREATE INDEX journal_key ON journal("key",id)',
        f'''CREATE TABLE runs ({text('namespace',64)}, {fixed('id',64)},
            state {large_text} NOT NULL CHECK({valid_json} AND octet_length(state)<=1048576),
            status VARCHAR(9){collate} NOT NULL CHECK(status IN {STATUSES!r}),
            {text('target',256)}, {text('workflow',64)}, {timestamp('created')}, {timestamp('available')},
            {fixed('delivery',32)}, {fixed('token',32,True)}, {timestamp('lease_until',True)},
            PRIMARY KEY(namespace,id), CHECK((token IS NULL)=(lease_until IS NULL)),
            CHECK(status='running' OR token IS NULL), {', '.join(identity)}){suffix}''',
        'CREATE INDEX runs_delivery ON runs(namespace,status,available,created,id)',
        'CREATE INDEX runs_expired ON runs(namespace,status,lease_until,id)',
        'CREATE INDEX runs_search ON runs(namespace,status,created,id)',
        'CREATE INDEX runs_target ON runs(namespace,target,created,id)',
        f'''CREATE TABLE admissions ({text('namespace',64)}, {fixed('run_id',64)},
            journal_id {integer} NOT NULL UNIQUE CHECK(journal_id BETWEEN 1 AND 9223372036854775807),
            {text('organization',128)}, {text('subject',128)}, {text('rule',64)},
            {fixed('revision',32)}, {text('event_id',128)}, mode VARCHAR(4){collate} NOT NULL CHECK(mode IN ('real','test')),
            PRIMARY KEY(namespace,run_id), FOREIGN KEY(namespace,run_id) REFERENCES runs(namespace,id),
            FOREIGN KEY(journal_id) REFERENCES journal(id)){suffix}''',
        'CREATE INDEX admissions_owner ON admissions(organization,subject,rule,namespace,revision,run_id)',
    ]
    # This trigger checks BOTH sides of the committed evidence before indexing it.
    comparisons = [('r.state','attribution.subject','subject'),('r.state','attribution.organization','organization'),
                   ('r.state','execution.rule','rule'),('r.state','execution.revision','revision'),
                   ('r.state','execution.event_id','event_id'),('j.value','run_id','run_id'),
                   ('j.value','author','subject'),('j.value','organization','organization'),('j.value','revision','revision')]
    equalities = ' AND '.join(extracted(column,path)+'=NEW.'+field for column,path,field in comparisons)
    issuer, operation = extracted('r.state','attribution.issuer'), extracted('j.value','operation')
    test_condition = ' AND '.join(
        f"{extracted(column,'test_context.test',True)}='true'::jsonb" if pg else
        f"JSON_TYPE({extracted(column,'test_context.test',True)})='BOOLEAN' AND {extracted(column,'test_context.test')}='true'"
        for column in ('r.state','j.value'))
    exists = f'''EXISTS (SELECT 1 FROM runs r JOIN journal j ON j.id=NEW.journal_id
        WHERE r.namespace=NEW.namespace AND r.id=NEW.run_id AND {equalities}
        AND ((NEW.mode='real' AND {issuer}='atropos.rules' AND {operation}='dispatch'
              AND {extracted('r.state','test_context',True)} IS NULL)
          OR (NEW.mode='test' AND {issuer}='atropos.tests' AND {operation}='test_run' AND {test_condition}
              AND {extracted('r.state','test_context.id')}=NEW.run_id AND {extracted('j.value','test_context.id')}=NEW.run_id)))'''
    changes = ' OR '.join([f'NEW.{column}<>OLD.{column}' for column in ('namespace','id','target','workflow','created')]
        + [mismatch(extracted('NEW.state',path,True),extracted('OLD.state',path,True))
           for path in ('attribution','execution','test_context')])
    if pg:
        for name, table, condition, issue in (
                ('admissions_evidence','admissions','NOT '+exists,'invalid_intervention_evidence'),
                ('admissions_immutable','admissions','TRUE','immutable_admission'),
                ('run_identity_immutable','runs',changes,'immutable_run_identity')):
            ddl += [f'''CREATE FUNCTION {name}_check() RETURNS trigger LANGUAGE plpgsql AS $body$
                BEGIN IF {condition} THEN RAISE EXCEPTION '{issue}' USING ERRCODE='23514'; END IF;
                RETURN NEW; END $body$''',
                f'''CREATE TRIGGER {name} BEFORE {'INSERT' if name=='admissions_evidence' else 'UPDATE'}
                ON {table} FOR EACH ROW EXECUTE FUNCTION {name}_check()''']
    else:
        # MySQL/MariaDB prohibit CHECK on AUTO_INCREMENT. Check the assigned
        # value AFTER INSERT, when an omitted id has its real positive value.
        ddl.append('''CREATE TRIGGER journal_id_positive AFTER INSERT ON journal FOR EACH ROW
            BEGIN IF NEW.id<1 OR NEW.id>9223372036854775807 THEN
            SIGNAL SQLSTATE '23000' SET MESSAGE_TEXT='invalid_journal_id'; END IF; END''')
        ddl.append('''CREATE TRIGGER journal_immutable BEFORE UPDATE ON journal FOR EACH ROW
            SIGNAL SQLSTATE '23000' SET MESSAGE_TEXT='immutable_journal' ''')
        for name, table, condition, issue in (
                ('admissions_evidence','admissions','NOT '+exists,'invalid_intervention_evidence'),
                ('admissions_immutable','admissions','TRUE','immutable_admission'),
                ('run_identity_immutable','runs',changes,'immutable_run_identity')):
            ddl.append(f'''CREATE TRIGGER {name} BEFORE {'INSERT' if name=='admissions_evidence' else 'UPDATE'}
                ON {table} FOR EACH ROW BEGIN IF {condition} THEN
                SIGNAL SQLSTATE '23000' SET MESSAGE_TEXT='{issue}'; END IF; END''')
    return ddl
